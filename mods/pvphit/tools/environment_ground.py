"""Reproduce the original 24-pixel environment kit and additive TEMPERAT copy.

No Blender perspective/vehicle scaling is used for planar ground. PNG pixels
and embedded sheet metadata are produced with the standard library only.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import re
import struct
import zlib

MOD = Path(__file__).resolve().parents[1]
FIRST_ID = 60000
NAMES = [f'ash-{i}' for i in range(4)] + [f'paving-{i}' for i in range(4)] + [
    'damaged-0', 'damaged-1', 'edge-n', 'edge-e', 'edge-s', 'edge-w',
    'outer-ne', 'outer-se', 'outer-sw', 'outer-nw',
    'inner-ne', 'inner-se', 'inner-sw', 'inner-nw', 'drain-ns', 'drain-ew']
IDS = {name: FIRST_ID + i for i, name in enumerate(NAMES)}


def noise(x, y, seed):
    n = (x * 374761393 + y * 668265263 + seed * 1442695041) & 0xffffffff
    n = ((n ^ (n >> 13)) * 1274126177) & 0xffffffff
    return ((n ^ (n >> 16)) % 101) / 100


def pixel(name, x, y):
    # All variations agree at tile boundaries, avoiding visible noise seams.
    seed = int(name[-1]) if name[-1].isdigit() and 2 < x < 21 and 2 < y < 21 else 0
    fine = noise(x, y, seed) - .5
    ash = tuple(int(c + fine * 7 + 2 * math.sin(x * .35) * math.sin(y * .35)) for c in (66, 65, 61))
    slab = tuple(int(c + fine * 4) for c in (93, 95, 89))
    if x == 0 or y == 0:
        slab = (77, 79, 74)
    elif x == 1 or y == 1:
        slab = (100, 101, 94)
    if name.startswith('ash'):
        return (*ash, 255)
    if name.startswith('damaged'):
        shift = int(name[-1]) * 7
        if 4 < x < 20 and 4 < y < 20 and abs(x - (8 + (y + shift) // 4)) <= (y % 3 == 0):
            slab = (64, 65, 61)
    dist = {'n': y, 'e': 23-x, 's': 23-y, 'w': x}
    blend = 1.0
    if name.startswith('edge-'):
        blend = min(1, dist[name[-1]] / 4)
    elif name.startswith('outer-'):
        blend = min(1, min(dist[d] for d in name[-2:]) / 4)
    elif name.startswith('inner-'):
        blend = min(1, math.hypot(*(dist[d] for d in name[-2:])) / 5)
    if name.startswith('drain'):
        p = x if name.endswith('ns') else y
        q = y if name.endswith('ns') else x
        if 9 <= p <= 14:
            slab = (53, 57, 55) if q % 4 < 2 else (77, 81, 77)
        elif p in (8, 15):
            slab = (111, 111, 100)
    return (*(round(a * (1-blend) + b * blend) for a, b in zip(ash, slab)), 255)


def png(path, width, height, pixels, metadata=None):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind+data))
    data = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0))
    for key, value in (metadata or {}).items():
        data += chunk(b'tEXt', key.encode()+b'\0'+str(value).encode())
    raw = b''.join(b'\0'+bytes(pixels[y*width*4:(y+1)*width*4]) for y in range(height))
    path.write_bytes(data + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def build(output):
    art = output/'art/environment'; art.mkdir(parents=True, exist_ok=True)
    pixels = bytearray()
    for row in range(3):
        for y in range(24):
            for col in range(8):
                for x in range(24):
                    pixels.extend(pixel(NAMES[row*8+col], x, y))
    png(art/'ground.png', 192, 72, pixels, {'FrameSize': '24,24', 'FrameAmount': 24})
    (art/'ground.yaml').write_text('FrameSize: 24,24\nFrameAmount: 24\n')
    original = (MOD.parent/'ra/tilesets/temperat.yaml').read_bytes()
    existing = {int(i) for i in re.findall(rb'\n\t\tId: (\d+)', original)}
    assert not existing.intersection(IDS.values()), 'Template ID collision'
    text = original.decode() + '\n# Original ashbound transfer yard additions; generated by environment_ground.py.\n'
    for index, name in enumerate(NAMES):
        color = '42413D' if name.startswith('ash') else '5D5F59'
        text += (f'\tTemplate@{IDS[name]}:\n\t\tId: {IDS[name]}\n'
                 '\t\tImages: pvphit|art/environment/ground.png\n'
                 f'\t\tFrames: {index}\n\t\tSize: 1,1\n\t\tCategories: Terrain\n'
                 f'\t\tTiles:\n\t\t\t0: Clear\n\t\t\t\tMinColor: {color}\n\t\t\t\tMaxColor: {color}\n')
    (output/'tilesets').mkdir(exist_ok=True)
    (output/'tilesets/temperat-industrial.yaml').write_text(text)
    manifest = {'tile_size': [24,24], 'scale': 1, 'terrain_type': 'Clear',
                'inherited_sha256': hashlib.sha256(original).hexdigest(), 'templates': IDS,
                'ground_sha256': hashlib.sha256((art/'ground.png').read_bytes()).hexdigest(),
                'generator_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
    (art/'ground-manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-root', type=Path, default=MOD)
    build(parser.parse_args().output_root)
