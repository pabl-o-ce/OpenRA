"""Validate and embed original cosmetic weapon effect sheets; no balance edits."""
from pathlib import Path
import argparse
import hashlib
import json
import os
import subprocess
import tempfile
from pack_vehicles import metadata, run, DIRECTIONS

MOD=Path(__file__).resolve().parents[1];ROOT=MOD.parents[1];ART=MOD/'art/motion-effects'
SPECS={}
for n in ('scout','tank','siege'):
    SPECS[n+'-muzzle']=(6,1,40);SPECS[n+'-impact']=(10,1,60);SPECS[n+'-shot']=(1,32,40)
for n in ('scout','hauler','tank','siege'): SPECS[n+'-death']=(12,1,80)


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--dotnet',default='dotnet');args=p.parse_args()
    status=json.loads((ART/'render-status.json').read_text())
    if status.get('running') or status.get('error') or status['done']!=status['total']: raise ValueError('Incomplete effect render')
    hashes={};files={}
    for n,(length,facings,tick) in SPECS.items():
        paths=[ART/'frames'/n/f'{i:03d}.png' for i in range(length*facings)]
        if set(paths)!=set((ART/'frames'/n).glob('*.png')): raise ValueError('Incomplete frames '+n)
        pixels=[]
        for path in paths:
            if run('magick','identify','-format','%wx%h',path)!=b'128x128': raise ValueError('Wrong canvas')
            data=run('magick',path,'-depth','8','RGBA:-');alpha=data[3::4]
            if len(data)!=65536: raise ValueError('Wrong pixel count')
            bounds=[i for i,a in enumerate(alpha) if a]
            if bounds and any(i%128<2 or i%128>125 or i//128<2 or i//128>125 for i in bounds): raise ValueError('Clipped '+str(path))
            pixels.append(data);hashes[str(path.relative_to(ART))]=hashlib.sha256(path.read_bytes()).hexdigest()
        if length>1 and len(set(pixels))<length-1: raise ValueError('Frozen effect '+n)
        files[n]=paths
    env=dict(os.environ,ENGINE_DIR=str(ROOT))
    with tempfile.TemporaryDirectory(prefix='.pack-',dir=ART) as d:
        stage=Path(d);lines=['# Generated by tools/pack_weapon_visuals.py. Cosmetic only.']
        for n,(length,facings,tick) in SPECS.items():
            out=stage/(n+'.png')
            run('magick','montage',*files[n],'-background','none','-tile','8x','-geometry','128x128+0+0','PNG32:'+str(out))
            out.with_suffix('.yaml').write_text(f'FrameSize: 128,128\nFrameAmount: {length*facings}\n')
            subprocess.run([args.dotnet,str(ROOT/'bin/OpenRA.Utility.dll'),'pvphit','--png-sheet-import',str(out)],cwd=ROOT,env=env,check=True,stdout=subprocess.DEVNULL)
            metadata(out,length*facings)
            muzzle=n.endswith('-muzzle');image='fc-'+n.removesuffix('-muzzle') if muzzle else 'fc-'+n
            seq='muzzle' if muzzle else 'idle'
            frames=DIRECTIONS if facings==32 else list(range(length))
            lines.extend(['',image+':',f'\t{seq}:',f'\t\tFilename: pvphit|art/motion-effects/{n}.png','\t\tScale: 0.5','\t\tOffset: 0,0',
                f'\t\tFacings: {facings}','\t\tUseClassicFacings: false','\t\tFrames: '+','.join(map(str,frames)),f'\t\tLength: {length}',f'\t\tTick: {tick}'])
        for path in stage.iterdir(): os.replace(path,ART/path.name)
        (MOD/'sequences/motion-effects.yaml').write_text('\n'.join(lines)+'\n')
        source=MOD/'art/source/effects/weapon-effects.blend'
        (ART/'export-manifest.json').write_text(json.dumps({'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'frames':hashes,'frame_size':[128,128],'scale':.5,'seed':600},indent=2)+'\n')
    print('Validated and packed '+str(len(hashes))+' effect frames')


if __name__=='__main__':main()
