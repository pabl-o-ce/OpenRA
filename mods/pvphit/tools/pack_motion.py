"""Validate and pack only FC6 animation sheets; --assets supports staged review."""
from pathlib import Path
import argparse
import hashlib
import json
import os
import subprocess
import tempfile
from pack_vehicles import rgba, metadata, run, DIRECTIONS

MOD=Path(__file__).resolve().parents[1]
ROOT=MOD.parents[1]
ART=MOD/'art/motion'
LAYERS={'hauler':{'body':1,'move':4,'harvest':4,'unload':4},
        'scout':{'body':1,'move':4},
        'siege':{'body':1,'move':4,'fire':5,'make':5,'deployed':1},
        'tank':{'body':1,'move':4,'turret':1,'wreck':1}}
TICKS={'move':80,'harvest':80,'unload':80,'fire':80,'make':400}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--assets',nargs='+',choices=LAYERS,default=list(LAYERS))
    parser.add_argument('--dotnet',default='dotnet')
    parser.add_argument('--validate-only',action='store_true')
    args=parser.parse_args()
    hashes={}; paths={}; pixels={}
    for n in args.assets:
        receipt=json.loads((ART/f'sprites-{n}.json').read_text())
        if receipt.get('running') or receipt.get('error') or receipt['done']!=receipt['total'] or n not in receipt['assets']:
            raise ValueError('Incomplete render: '+n)
        for l,count in LAYERS[n].items():
            files=[ART/'frames'/n/l/f'{i:03d}.png' for i in range(32*count)]
            if set(files)!=set((ART/'frames'/n/l).glob('*.png')): raise ValueError('Incomplete/extra frames')
            paths[n,l]=files; pixels[n,l]=[rgba(p) for p in files]
            for p in files: hashes[str(p.relative_to(ART))]=hashlib.sha256(p.read_bytes()).hexdigest()
            if count>1:
                for f in range(32):
                    if len(set(pixels[n,l][f*count:(f+1)*count]))<2: raise ValueError(f'Frozen {n}/{l}/{f}')
        if n=='siege':
            for f in range(32):
                if pixels[n,'make'][f*5]!=pixels[n,'body'][f] or pixels[n,'make'][f*5+4]!=pixels[n,'deployed'][f]:
                    raise ValueError(f'Deployment endpoint mismatch: {f}')
                if pixels[n,'fire'][f*5]!=pixels[n,'deployed'][f] or pixels[n,'fire'][f*5+4]!=pixels[n,'deployed'][f]:
                    raise ValueError(f'Firing endpoint mismatch: {f}')
        for f in range(32):
            if pixels[n,'move'][f*4]!=pixels[n,'body'][f]: raise ValueError(f'Movement rest mismatch: {n}/{f}')
    print(f'Validated {len(hashes)} animation frames',flush=True)
    if args.validate_only: return
    env=dict(os.environ,ENGINE_DIR=str(ROOT))
    with tempfile.TemporaryDirectory(prefix='.pack-',dir=ART) as tmp:
        stage=Path(tmp)
        for n in args.assets:
            lines=['# Generated by tools/pack_motion.py; full-canvas uniform facings.',f'fc-{n}:']
            for l,count in LAYERS[n].items():
                out=stage/n/(l+'.png');out.parent.mkdir(exist_ok=True)
                run('magick','montage',*paths[n,l],'-background','none','-tile','8x','-geometry','128x128+0+0','PNG32:'+str(out))
                out.with_suffix('.yaml').write_text(f'FrameSize: 128,128\nFrameAmount: {count*32}\n')
                subprocess.run([args.dotnet,str(ROOT/'bin/OpenRA.Utility.dll'),'pvphit','--png-sheet-import',str(out)],cwd=ROOT,env=env,check=True,stdout=subprocess.DEVNULL)
                metadata(out,count*32)
                if n=='tank' and l=='wreck': lines.extend(['','fc-tank-wreck:'])
                seq='idle' if l=='body' or (n=='tank' and l=='wreck') else l
                frames=[f*count+k for f in DIRECTIONS for k in range(count)]
                lines.extend([f'\t{seq}:',f'\t\tFilename: pvphit|art/motion/{n}/{l}.png','\t\tScale: 0.5','\t\tOffset: 0,-7',
                    '\t\tFacings: 32','\t\tUseClassicFacings: false','\t\tFrames: '+','.join(map(str,frames)),f'\t\tLength: {count}'])
                if l in TICKS: lines.append(f'\t\tTick: {TICKS[l]}')
            (stage/(n+'.yaml')).write_text('\n'.join(lines)+'\n')
        for n in args.assets:
            (ART/n).mkdir(exist_ok=True)
            for p in (stage/n).iterdir(): os.replace(p,ART/n/p.name)
            os.replace(stage/(n+'.yaml'),MOD/'sequences'/('motion-'+n+'.yaml'))
            src=MOD/'art/source/motion'/(n+'.blend')
            manifest={'source':str(src.relative_to(MOD)),'source_sha256':hashlib.sha256(src.read_bytes()).hexdigest(),
                      'frames':{p:h for p,h in hashes.items() if p.startswith('frames/'+n+'/')},
                      'frame_size':[128,128],'scale':.5,'offset':[0,-7],'ortho_scale':4.9,'engine_source_facings':DIRECTIONS,
                      'ordering':'facing-major','ticks_ms':TICKS,'renderer':{'engine':'Cycles','samples':32 if n=='tank' else 24}}
            (ART/n/'export-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')


if __name__=='__main__': main()
