"""Pack only the three core-building exports; never regenerate earlier assets.

Run after Blender MCP completes start_render('sprites'). XDG_CONFIG_HOME must
resolve installed RA content, as for the existing packers.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import re
import subprocess

MOD = Path(__file__).resolve().parents[1]
ROOT = MOD.parents[1]
ART = MOD / 'art/core-buildings'
ASSETS = ('hq', 'generator', 'processor')
LAYERS = (('idle',4,80),('damaged-idle',4,80),('make',5,400))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dotnet', default='dotnet')
    args = parser.parse_args()
    status = json.loads((ART/'render-status.json').read_text())
    if status.get('running') or status.get('error') or status['done'] != status['total']:
        raise RuntimeError('Render has not completed successfully')
    # Validate everything before creating or replacing any packed output.
    frames = {}
    for asset in ASSETS:
        for layer,count,_ in LAYERS:
            paths = [ART/'frames'/asset/layer/f'{i:02d}.png' for i in range(count)]
            for path in paths:
                dimensions = subprocess.check_output(['magick', 'identify', '-format', '%wx%h %[channels]', str(path)], text=True)
                if not dimensions.startswith('256x256 ') or 'a' not in dimensions.split()[1]:
                    raise ValueError(f'Invalid sprite dimensions/mode: {path}')
                bounds = subprocess.check_output(['magick',str(path),'-alpha','extract','-format','%@','info:'],text=True)
                match = re.fullmatch(r'(\d+)x(\d+)\+(\d+)\+(\d+)',bounds)
                if not match:
                    raise ValueError(f'Invalid sprite bounds: {path}: {bounds}')
                w,h,x,y = map(int,match.groups())
                if not w or not h or x==0 or y==0 or x+w>=256 or y+h>=256:
                    raise ValueError(f'Empty or clipped sprite: {path}')
            frames[asset,layer] = paths
    # Detect frozen machinery and construction endpoint jumps before packing.
    def same_pixels(first, second):
        result = subprocess.run(['magick','compare','-metric','AE',str(first),str(second),'null:'],
                                capture_output=True,text=True)
        if result.returncode not in (0,1):
            raise RuntimeError(result.stderr)
        return result.returncode == 0
    for asset in ASSETS:
        for layer in ('idle','damaged-idle'):
            first,*others = frames[asset,layer]
            if any(same_pixels(first,other) for other in others):
                raise ValueError(f'Frozen operating frame: {asset}/{layer}')
        if not same_pixels(frames[asset,'idle'][0],frames[asset,'make'][-1]):
            raise ValueError(f'Construction endpoint does not match idle: {asset}')
        if same_pixels(frames[asset,'idle'][0],frames[asset,'damaged-idle'][0]):
            raise ValueError(f'Missing damage state: {asset}')
    env = dict(os.environ, ENGINE_DIR=str(ROOT))
    sequences = ['# Generated by tools/pack_core_buildings.py']
    hashes = {}
    for asset in ASSETS:
        dest = ART/asset
        dest.mkdir(parents=True,exist_ok=True)
        sequences.append(f'\nfc-{asset}:')
        for layer,count,tick in LAYERS:
            for path in frames[asset,layer]:
                hashes[str(path.relative_to(ART))] = hashlib.sha256(path.read_bytes()).hexdigest()
            output = dest/f'{layer}.png'
            subprocess.run(['magick','montage',*map(str,frames[asset,layer]),'-background','none',
                            '-tile',f'{count}x','-geometry','256x256+0+0','PNG32:'+str(output)],check=True)
            output.with_suffix('.yaml').write_text(f'FrameSize: 256,256\nFrameAmount: {count}\n')
            subprocess.run([args.dotnet,str(ROOT/'bin/OpenRA.Utility.dll'),'pvphit',
                            '--png-sheet-import',str(output)],env=env,cwd=ROOT,check=True)
            sequences.extend([f'\t{layer}:',f'\t\tFilename: pvphit|art/core-buildings/{asset}/{layer}.png',
                              '\t\tScale: 0.5','\t\tOffset: 0,-14',f'\t\tLength: {count}',f'\t\tTick: {tick}'])
        # Retain the old explicitly named damaged sequence as a one-frame alias.
        sequences.extend(['\tdamaged:',f'\t\tFilename: pvphit|art/core-buildings/{asset}/damaged-idle.png',
                          '\t\tScale: 0.5','\t\tOffset: 0,-14','\t\tLength: 1'])
        subprocess.run(['magick',str(frames[asset,'idle'][0]),'-trim','+repage','-resize','60x44',
                        '-gravity','center','-background','#20272c','-extent','64x48',
                        'PNG32:'+str(dest/'icon.png')],check=True)
        sequences.extend(['\ticon:',f'\t\tFilename: pvphit|art/core-buildings/{asset}/icon.png'])
    (MOD/'sequences/core-buildings.yaml').write_text('\n'.join(sequences)+'\n')
    (ART/'export-manifest.json').write_text(json.dumps({'frame_size':[256,256],
        'assets':ASSETS,'frames':hashes},indent=2)+'\n')


if __name__ == '__main__':
    main()
