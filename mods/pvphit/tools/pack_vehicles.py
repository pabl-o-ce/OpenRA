"""Validate and stage the FC5 vehicle sheets before replacing owned outputs.

Uses ImageMagick and this checkout's OpenRA.Utility; no Pillow dependency.
--validate-only checks exports without writing packed assets.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import subprocess
import tempfile
import struct

MOD = Path(__file__).resolve().parents[1]
ROOT = MOD.parents[1]
ART = MOD/'art/vehicles'
LAYERS = {'hauler': {'body':1,'wreck':1},
          'scout': {'body':1,'turret':1,'wreck':1},
          'siege': {'body':1,'make':5,'deployed':1,'wreck':1}}
DIRECTIONS = list(range(16,32))+list(range(16))


def run(*args):
    return subprocess.check_output(list(map(str,args)))


def rgba(path):
    dimensions = run('magick','identify','-format','%wx%h %[channels]',path).decode()
    if not dimensions.startswith('128x128 ') or 'a' not in dimensions.split()[1]:
        raise ValueError(f'Invalid dimensions/mode: {path}: {dimensions}')
    data = run('magick',path,'-depth','8','RGBA:-')
    if len(data)!=128*128*4: raise ValueError(f'Invalid pixel data: {path}')
    alpha = data[3::4]
    bounds = [i for i,a in enumerate(alpha) if a]
    if not bounds: raise ValueError(f'Empty sprite: {path}')
    xs,ys = [i%128 for i in bounds],[i//128 for i in bounds]
    if min(xs)<2 or min(ys)<2 or max(xs)>125 or max(ys)>125:
        raise ValueError(f'Clipped sprite: {path}')
    return data


def metadata(path, count):
    # This fork stores each YAML field as a PNG tEXt entry.
    raw = path.read_bytes()
    offset = 8
    fields = {}
    while offset < len(raw):
        size = struct.unpack('>I',raw[offset:offset+4])[0]
        kind = raw[offset+4:offset+8]
        value = raw[offset+8:offset+8+size]
        if kind==b'tEXt':
            key,text = value.split(b'\0',1)
            fields[key.decode()] = text.decode()
        offset += size+12
    if fields.get('FrameSize')!='128,128' or fields.get('FrameAmount')!=str(count):
        raise ValueError(f'Missing embedded frame metadata: {path}')


def validate():
    status = json.loads((ART/'sprites-status.json').read_text())
    if status.get('running') or status.get('error') or status.get('done')!=status.get('total'):
        raise ValueError('Sprite rendering has not completed successfully')
    paths,pixels,hashes = {},{},{}
    for name,layers in LAYERS.items():
        for layer,length in dict(layers,icon=0).items():
            count = 32*length if length else 1
            key = name,layer
            paths[key] = [ART/'frames'/name/layer/f'{i:03d}.png' for i in range(count)]
            actual = set((ART/'frames'/name/layer).glob('*.png'))
            if actual!=set(paths[key]): raise ValueError(f'Unexpected/incomplete frames: {key}')
            pixels[key] = [rgba(p) for p in paths[key]]
            for p in paths[key]: hashes[str(p.relative_to(ART))] = hashlib.sha256(p.read_bytes()).hexdigest()
        for i in range(32):
            if pixels[name,'body'][i]==pixels[name,'wreck'][i]:
                raise ValueError(f'Wreck identical to body: {name}/{i}')
    for facing in range(32):
        states = pixels['siege','make'][facing*5:facing*5+5]
        if states[0]!=pixels['siege','body'][facing] or states[-1]!=pixels['siege','deployed'][facing]:
            raise ValueError(f'Siege endpoint mismatch: {facing}')
        if len(set(states))!=5: raise ValueError(f'Frozen deployment: {facing}')
    # Shared frame origin and safe alpha bounds imply every hull/turret union
    # remains in-frame for all 32 x 32 combinations (no trimming on either layer).
    for key in (('scout','body'),('scout','turret')):
        if len(set(pixels[key]))!=32: raise ValueError(f'Duplicate scout directions: {key}')
    return paths,hashes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dotnet',default='dotnet')
    parser.add_argument('--validate-only',action='store_true')
    args = parser.parse_args()
    paths,hashes = validate()
    print(f'Validated {len(hashes)} RGBA frames; all facing/state bounds and siege endpoints pass.',flush=True)
    if args.validate_only: return
    env = dict(os.environ,ENGINE_DIR=str(ROOT))
    # No live sheets or overrides are touched until all staged imports succeed.
    with tempfile.TemporaryDirectory(prefix='vehicle-pack-',dir=ART) as temporary:
        staging = Path(temporary)
        lines = ['# Generated by tools/pack_vehicles.py. Uniform facings, facing-major animation.']
        for name,layers in LAYERS.items():
            dest = staging/name
            dest.mkdir()
            lines.append(f'\nfc-{name}:')
            for layer,length in layers.items():
                output = dest/f'{layer}.png'
                count = len(paths[name,layer])
                run('magick','montage',*paths[name,layer],'-background','none','-tile','8x',
                    '-geometry','128x128+0+0','PNG32:'+str(output))
                output.with_suffix('.yaml').write_text(f'FrameSize: 128,128\nFrameAmount: {count}\n')
                subprocess.run([args.dotnet,str(ROOT/'bin/OpenRA.Utility.dll'),'pvphit',
                                '--png-sheet-import',str(output)],env=env,cwd=ROOT,check=True,stdout=subprocess.DEVNULL)
                metadata(output,count)
                frames = [f*length+s for f in DIRECTIONS for s in range(length)]
                sequence = 'idle' if layer=='body' else layer
                lines.extend([f'\t{sequence}:',f'\t\tFilename: pvphit|art/vehicles/{name}/{layer}.png',
                    '\t\tScale: 0.5','\t\tOffset: 0,-7','\t\tFacings: 32','\t\tUseClassicFacings: false',
                    '\t\tFrames: '+','.join(map(str,frames)),f'\t\tLength: {length}'])
                if layer=='make': lines.append('\t\tTick: 400')
            run('magick',paths[name,'icon'][0],'-trim','+repage','-resize','60x44',
                '-gravity','center','-background','#20272c','-extent','64x48','PNG32:'+str(dest/'icon.png'))
            lines.extend(['\ticon:',f'\t\tFilename: pvphit|art/vehicles/{name}/icon.png'])
        sequence_text = '\n'.join(lines)+'\n'
        manifest = {'frame_size':[128,128],'scale':.5,'offset':[0,-7],'ortho_scale':4.9,
                    'source_forward':'-Y','source_rotation_degrees':11.25,'engine_source_facings':DIRECTIONS,
                    'deployment':{'length':5,'tick_ms':400,'ordering':'facing-major','withdrawal':'reverse make'},
                    'renderer':{'engine':'Cycles','device':'CPU','samples':24,'seed':0},
                    'sources':{name:hashlib.sha256((MOD/'art/source/vehicles'/f'{name}.blend').read_bytes()).hexdigest()
                               for name in LAYERS},'frames':hashes}
        for name in LAYERS:
            (ART/name).mkdir(exist_ok=True)
            for p in (staging/name).iterdir(): os.replace(p,ART/name/p.name)
        (MOD/'sequences/vehicles.yaml').write_text(sequence_text)
        (ART/'export-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print('Packed only vehicle outputs and sequences/vehicles.yaml.',flush=True)


if __name__=='__main__': main()
