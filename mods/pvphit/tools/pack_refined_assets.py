"""Pack the live Blender MCP visual pass without touching the earlier assets.

XDG_CONFIG_HOME must point to a configured OpenRA content directory.
"""
from pathlib import Path
import argparse
import subprocess

MOD = Path(__file__).resolve().parents[1]
ROOT = MOD.parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dotnet', default='dotnet')
    parser.add_argument('--pass-name', choices=('refined','heavy'), default='refined')
    args = parser.parse_args()
    art = MOD/'art'/args.pass_name
    sequences = {}

    def sheet(asset, layer, count, size):
        frames = [art / 'frames' / asset / layer / f'{i:02d}.png' for i in range(count)]
        if not all(p.is_file() for p in frames):
            raise RuntimeError(f'Incomplete render: {asset}/{layer}')
        dest = art / asset / f'{layer}.png'
        dest.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(['magick', 'montage', *map(str, frames), '-background', 'none',
                        '-tile', f'{min(count,8)}x', '-geometry', f'{size}x{size}+0+0',
                        'PNG32:' + str(dest)], check=True)
        dest.with_suffix('.yaml').write_text(f'FrameSize: {size},{size}\nFrameAmount: {count}\n')
        subprocess.run([args.dotnet, str(ROOT/'bin/OpenRA.Utility.dll'), 'pvphit',
                        '--png-sheet-import', str(dest)], cwd=ROOT, check=True)
        return 'pvphit|' + str(dest.relative_to(MOD))

    def seq(actor, name, filename, extra=()):
        sequences.setdefault(actor, []).extend([f'\t{name}:',f'\t\tFilename: {filename}',
                                                *['\t\t'+v for v in extra]])

    for layer, name in [('body','idle'),('turret','turret'),('wreck','idle')]:
        actor = 'fc-tank-wreck' if layer == 'wreck' else 'fc-tank'
        seq(actor,name,sheet('tank',layer,32,128))
    for layer,name,count in [('body','idle',4),('damaged-body','damaged-idle',4),
                             ('door','build-top',5),('damaged-door','damaged-build-top',5),
                             ('make','make',5)]:
        seq('fc-factory',name,sheet('factory',layer,count,256),
            ['Scale: 0.5','Offset: 0,-14',f'Length: {count}',f'Tick: {400 if layer=="make" else 80}'])
    for asset in ('barrier','pressure-skid','pipe','pallet','concrete','road','drain','hazard'):
        if args.pass_name=='heavy':continue
        floor = asset in ('concrete','road','drain','hazard')
        seq('fc-yard-'+asset,'idle',sheet(asset,'all',1,48 if floor else 128),
            ['Scale: 0.5',f'Offset: 0,{0 if floor else -7}',*(['ZOffset: -10000'] if floor else [])])
    for asset in ('tank','factory'):
        source = art/'frames'/asset/('all' if asset=='tank' else 'make')/'04.png'
        dest = art/asset/'icon.png'
        subprocess.run(['magick',str(source),'-trim','+repage','-resize','60x44','-gravity','center',
                        '-background','#20272c','-extent','64x48','PNG32:'+str(dest)],check=True)
        seq('fc-'+asset,'icon','pvphit|'+str(dest.relative_to(MOD)))
    (MOD/'sequences'/f'{args.pass_name}.yaml').write_text('# Generated by tools/pack_refined_assets.py\n'+
        '\n\n'.join(name+':\n'+'\n'.join(lines) for name,lines in sequences.items())+'\n')


if __name__ == '__main__':
    main()
