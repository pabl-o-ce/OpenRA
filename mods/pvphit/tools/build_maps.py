def slice_rules():
    # Suppress the inherited build roster only on this map. Follow inheritance
    # so fake buildings and variants cannot leak through the construction menu.
    actors={}
    sources=[MOD.parent/'ra'/line.strip().split('|',1)[1]
             for line in (MOD/'mod.yaml').read_text().splitlines()
             if line.startswith('\tra|rules/')]
    for source in sources:
        actor=None
        for line in source.read_text().splitlines():
            if line and not line.startswith(('\t','#',' ')) and ':' in line:
                actor=line.split(':',1)[0]
                actors.setdefault(actor,[])
            elif actor and line.startswith('\t') and not line.startswith('\t\t'):
                actors[actor].append(line.strip())
    def buildable(name,seen=frozenset()):
        if name in seen:return False
        traits=actors.get(name,[])
        if '-Buildable:' in traits:return False
        if 'Buildable:' in traits:return True
        return any(buildable(t.split(':',1)[1].strip(),seen|{name})
                   for t in traits if t.startswith('Inherits'))
    text='''# Map-scoped slice rules; generated by tools/build_maps.py.
World:
\t-CrateSpawner:
\t-StartingUnits@mcvonly:
\t-StartingUnits@lightallies:
\t-StartingUnits@lightsoviet:
\t-StartingUnits@heavyallies:
\t-StartingUnits@heavysoviet:
\tStartingUnits@FURNACE:
\t\tClass: furnace
\t\tClassName: furnace-starting-units
\t\tFactions: kiln
\t\tBaseActor: fc.hq
\t\tBaseActorOffset: -1,-1
\tSpawnStartingUnits:
\t\tStartingUnitsClass: furnace
\t\tDropdownLocked: true
\t\tDropdownVisible: false
\tFaction@kiln:
\t\tSelectable: true
\tResourceRenderer:
\t\tResourceTypes:
\t\t\tOre:
\t\t\t\tImage: fc-slag
\t\t\t\tSequences: idle
\t\t\t\tPalette: player
\t\t\t\tName: resource-furnace-slag
Player:
\tPlayerResources:
\t\tDefaultCash: 5000
\t\tDefaultCashDropdownLocked: true
\tClassicProductionQueue@Building:
\t\tSpeedUp: false
\tClassicProductionQueue@Vehicle:
\t\tSpeedUp: false
'''
    for faction in ('england','france','germany','russia','ukraine','random','randomallies','randomsoviet'):
        # Add world overrides before the Player node.
        text=text.replace('Player:\n',f'\tFaction@{faction}:\n\t\tSelectable: false\nPlayer:\n',1)
    for name in sorted(actors):
        if not name.startswith('^') and buildable(name):
            text+=f'{name}:\n\tBuildable:\n\t\tPrerequisites: ~disabled\n'
    (MOD/'rules/slice.yaml').write_text(text)

