from pathlib import Path
import struct

MOD = Path(__file__).resolve().parents[1]

def terrain(path, size, fields=()):
    # map.bin is column-major; flat maps omit the height channel.
    count = size * size
    header = struct.pack('<BHHIII', 2, size, size, 17, 0, 17 + count * 3)
    tiles = b''.join(struct.pack('<HB', 255, (x * 7 + y * 11) % 16)
                     for x in range(size) for y in range(size))
    resources = bytearray()
    for x in range(size):
        for y in range(size):
            present = any((x-cx)**2+(y-cy)**2<=radius**2 for cx,cy,radius in fields)
            resources.extend((1,12) if present else (0,0))
    path.write_bytes(header + tiles + resources)

